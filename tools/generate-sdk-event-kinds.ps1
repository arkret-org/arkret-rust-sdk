foreach ($entry in $entries) {
    Add-Line '    #[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]'
    Add-Line "    pub struct $($entry.Variant);"
    Add-Line "    impl $($entry.Variant) {"
    Add-Line "        pub const KIND: EventKind = EventKind::$($entry.Variant);"
