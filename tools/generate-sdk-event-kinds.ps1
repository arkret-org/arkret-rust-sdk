Add-Line "    pub fn descriptor(&self) -> Option<&'static EventKindDescriptor> {"
Add-Line '        EVENT_KIND_DESCRIPTORS'
Add-Line '            .binary_search_by_key(&self.as_str(), |descriptor| descriptor.kind)'
Add-Line '            .ok()'
