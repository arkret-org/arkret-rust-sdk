Add-Line "pub const EVENT_KIND_REGISTRY_SHA256: &str = `"$digest`";"
Add-Line
Add-Line '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]'
Add-Line 'pub enum EventRegistryCategory {'
