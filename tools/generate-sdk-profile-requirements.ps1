# arkret-spec/spec/v1/artifacts/profiles/conformance-profiles.json.
#
# Mirrors the style of tools/generate-sdk-event-kinds.ps1 but produces a
# richer module exposing per-profile inheritance, required operations / event
# kinds / schemas / fixtures / features / capability actions / cells /
# constraint kinds together with a structured validator.
#
# The artifact field `required_endpoints` is surfaced as `required_operations`
# to match the rest of the Arkret SDK vocabulary (operation registry, etc).
# Constraint kinds aggregate `required_constraint_kinds` and
# `required_constraint_subkinds` from the artifact.

$profilesPath = Join-Path $ArtifactsDir "profiles\conformance-profiles.json"
if (!(Test-Path -LiteralPath $profilesPath)) {
    throw "conformance profile artifact not found: $profilesPath"
}

$raw = Get-Content -LiteralPath $profilesPath -Raw
$artifact = $raw | ConvertFrom-Json
$digest = (Get-FileHash -LiteralPath $profilesPath -Algorithm SHA256).Hash.ToLowerInvariant()
if ($null -eq $artifact.profile_requirements) {
    throw "conformance profile artifact missing top-level 'profile_requirements' object"
}

function Get-StringArray {
    param($Source, [string]$Field)
    if ($null -eq $Source) { return ,@() }
    $value = $Source.$Field
    if ($null -eq $value) { return ,@() }
    $arr = @($value | ForEach-Object { [string]$_ })
    return ,$arr
}

# PSCustomObject -> UTF-8-byte-sorted profile_id list.
