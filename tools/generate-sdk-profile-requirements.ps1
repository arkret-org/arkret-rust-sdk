function Format-RustStrSlice {
    param([string[]]$Values, [int]$Indent)
    $pad = ' ' * $Indent
    if ($Values.Count -eq 0) {
        return "&[]"
    }
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append("&[")
    [void]$sb.Append([Environment]::NewLine)
    foreach ($v in $Values) {
        $escaped = $v.Replace('\', '\\').Replace('"', '\"')
        [void]$sb.Append($pad)
        [void]$sb.Append('    "')
        [void]$sb.Append($escaped)
        [void]$sb.Append('",')
        [void]$sb.Append([Environment]::NewLine)
    }
    [void]$sb.Append($pad)
    [void]$sb.Append(']')
    return $sb.ToString()
}

function Escape-RustString {
    param([string]$Value)
    return $Value.Replace('\', '\\').Replace('"', '\"')
}

function Format-NonEventGrantAuthorityRules {
    param($Rules, [int]$Indent)
    if ($null -eq $Rules) {
        return "&[]"
    }
    $items = @($Rules)
    if ($items.Count -eq 0) {
        return "&[]"
    }
    $pad = ' ' * $Indent
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append("&[")
    [void]$sb.Append([Environment]::NewLine)
    foreach ($rule in $items) {
        [void]$sb.Append($pad)
        [void]$sb.Append("    NonEventGrantAuthorityRule {")
        [void]$sb.Append([Environment]::NewLine)
        foreach ($field in @(
            'issuer_action',
            'grantable_action',
            'required_registration_event_kind',
            'required_claimed_profile',
            'required_constraint_kind',
            'required_constraint_subkind',
            'subject_binding',
            'scope_binding',
            'epoch_binding',
            'requested_action_binding'
        )) {
            $value = Escape-RustString -Value ([string]$rule.$field)
            [void]$sb.Append($pad)
            [void]$sb.Append("        ${field}: `"$value`",")
            [void]$sb.Append([Environment]::NewLine)
        }
        $ownerAllowed = if ($rule.issuer_owner_authority_allowed) { "true" } else { "false" }
        [void]$sb.Append($pad)
        [void]$sb.Append("        issuer_owner_authority_allowed: $ownerAllowed,")
        [void]$sb.Append([Environment]::NewLine)
        [void]$sb.Append($pad)
        [void]$sb.Append("    },")
        [void]$sb.Append([Environment]::NewLine)
    }
    [void]$sb.Append($pad)
    [void]$sb.Append(']')
    return $sb.ToString()
}

