"""Embed the exact reachable current-result schema closure for native and wasm."""
import argparse
import copy
import json
from pathlib import Path
from urllib.parse import urldefrag, urljoin

parser = argparse.ArgumentParser()
parser.add_argument('--artifacts-dir', required=True)
parser.add_argument('--output', required=True)
args = parser.parse_args()
root = Path(args.artifacts_dir)
documents = {}
for path in (root / 'schemas').glob('*.json'):
    value = json.loads(path.read_text(encoding='utf-8'))
    documents[value['$id']] = value
start = 'https://arkret.org/v1/schemas/account-current-result.schema.json'
pending = [start]
seen = set()
pruned = {}

def scan(node, base):
    if isinstance(node, dict):
        base = urljoin(base, node['$id']) if isinstance(node.get('$id'), str) else base
        if isinstance(node.get('$ref'), str):
            pending.append(urljoin(base, node['$ref']))
        for key, value in node.items():
            if key != '$defs':
                scan(value, base)
    elif isinstance(node, list):
        for value in node:
            scan(value, base)

while pending:
    ref = pending.pop()
    if ref in seen:
        continue
    seen.add(ref)
    uri, fragment = urldefrag(ref)
    original = documents[uri]
    node = original
    parts = fragment.lstrip('/').split('/') if fragment else []
    for part in parts:
        part = part.replace('~1', '/').replace('~0', '~')
        node = node[int(part)] if isinstance(node, list) else node[part]
    if not parts:
        whole = copy.deepcopy(node)
        whole.pop('$defs', None)
        pruned.setdefault(uri, {}).update(whole)
    else:
        target = pruned.setdefault(uri, {'$id': uri, '$schema': original['$schema']})
        # Referenced fragments in the formal schema closure are definition paths.
        for part in parts[:-1]:
            target = target.setdefault(part, {})
        target[parts[-1]] = copy.deepcopy(node)
    scan(node, uri)

catalog = json.loads((root / 'registry/current-result-registry.json').read_text(encoding='utf-8'))
contracts = json.loads((root / 'registry/contract-registry.json').read_text(encoding='utf-8'))['event_kind_registry']['cell_contracts']
for row in catalog['families']:
    ref = row.get('value_schema_ref')
    value = None
    if ref:
        uri, fragment = urldefrag('https://arkret.org/v1/' + ref)
        value = documents[uri]
        for part in fragment.lstrip('/').split('/'):
            value = value[part]
    derived = bool(value and value.get('type') == 'object' and 'id' in value.get('required', []))
    if derived:
        subjects = {write['cell_subject']['kind'] for contract in contracts.values() for write in contract['cell_writes'] if write.get('cell_family') == row['cell_family']}
        if len(subjects) != 1 or not next(iter(subjects)).startswith('id:'):
            raise ValueError('Materialized object id needs an unambiguous typed-id subject: ' + row['cell_family'])
    row['materialized_id_from_subject'] = derived
    writes = [write for contract in contracts.values() for write in contract['cell_writes'] if write.get('cell_family') == row['cell_family']]
    # Contracts spell a singleton subject as JSON null, not an omitted key.
    row['singleton'] = bool(writes) and all(write.get('cell_subject') is None for write in writes)
bundle = {'documents': [pruned[key] for key in sorted(pruned)], 'families': catalog['families']}
wire = json.dumps(bundle, ensure_ascii=False, separators=(',', ':'))
output = Path(args.output)
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text('// Generated by tools/generate-current-result-schemas.py. Do not edit.\n'
                  'pub const MAX_ATOMIC_CURRENT_ENTRY_CANONICAL_BYTES: usize = ' + str(catalog['budgets']['max_atomic_entry_canonical_bytes']) + ';\n'
                  'pub const CURRENT_RESULT_SCHEMA_BUNDLE: &str = r########"' + wire + '"########;\n',
                  encoding='utf-8')
print(f'Generated current-result closure: {len(pruned)} documents, {len(wire.encode())} bytes')
